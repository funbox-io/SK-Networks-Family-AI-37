/* ── world 샘플 데이터베이스 구조 ───────────────────────────────────
   1) country         : 세계 각국의 정보
                        (국가코드, 국가명, 대륙, 인구, GDP 등)
   2) city            : 세계 주요 도시 정보
                        (도시ID, 도시명, 국가코드, 인구 등)
   3) countrylanguage : 각 국가별 사용 언어 정보
   ------------------------------------------------------------------ */

USE world;


-- 1) country 테이블의 전체 컬럼 조회
--    ※ * 는 모든 컬럼을 의미. 컬럼이 많아 화면이 넓게 출력됨
SELECT * FROM country;


-- 2) 특정 컬럼만 지정하여 조회 (국가명, 대륙, 인구)
--    ※ 실무에서는 필요한 컬럼만 지정하는 것이 성능·가독성에 유리
SELECT Name, Continent, Population FROM country;


