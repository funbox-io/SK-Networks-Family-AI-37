/* ===================================================================
   [08] 범위 · 목록 · 패턴 검색 — BETWEEN, IN, LIKE
   교재 : p.51 ~ p.55
   선행 : world 샘플 DB
   -------------------------------------------------------------------
   BETWEEN A AND B  : 연속된 범위 검색 (A 이상 B 이하)
   IN (값1, 값2 …)  : 지정한 목록 중 하나라도 일치하면 검색
   LIKE             : 문자열 부분 일치 패턴 검색 (와일드카드 활용)
   =================================================================== */


/* ── 와일드카드 정리 (p.51) ────────────────────────────────────────
   와일드카드 : 문자열의 특정 패턴을 유연하게 검색하기 위해 사용하는
               특수 문자. LIKE 연산자와 함께 사용되어 '정확히 일치하지
               않는' 부분 검색이나 형태 검색을 수행

   %  : 글자 수에 제한 없이 어떤 문자가 와도 허용
        ① LIKE '김%'   → '김'으로 시작하는 모든 문자 (김철수, 김, 김민준)
        ② LIKE '%김%'  → '김'이 포함된 모든 문자 (김철수, 서울김치)
        ③ LIKE '%김'   → '김'으로 끝나는 모든 문자 (허균김, 김)

   _  : 글자 수가 정확히 일치해야 하며, 언더바 개수만큼 글자 자리를 강제
        ① LIKE '김_'   → '김'으로 시작하는 총 2글자 (김민, 김수)
                         ※ '김철수'는 3글자라 조회 안 됨
        ② LIKE '_김'   → '김'으로 끝나는 총 2글자 (홍김, 박김)
        ③ LIKE '김__'  → '김'으로 시작하는 총 3글자 (김철수, 김민준)
   ------------------------------------------------------------------ */

USE world;


-- 1) 인구가 1,000만 ~ 2,000만 사이인 국가 조회 (BETWEEN)
--    ※ 경계값 포함 (10000000 이상 20000000 이하)
SELECT Name, Population
FROM country
WHERE Population BETWEEN 10000000 AND 20000000;


-- 2) 대륙이 'Asia', 'Europe', 'North America' 중 하나인 국가 조회 (IN)
--    ※ OR를 여러 번 쓰는 대신 간결하게 표현
SELECT Name, Continent
FROM country
WHERE Continent IN ('Asia', 'Europe', 'North America');


-- 3) 국가명이 'South'로 시작하는 국가 조회 (LIKE)
--    ※ 'South%' → South 뒤에 어떤 글자가 몇 개 오든 허용
SELECT Name
FROM country
WHERE Name LIKE 'South%';
