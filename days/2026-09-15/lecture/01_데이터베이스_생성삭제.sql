/* ===================================================================
   [01] 데이터베이스 생성 / 삭제   ※ DDL
   교재 : p.19 ~ p.22
   선행 : 없음 (Workbench 접속만 되어 있으면 실행 가능)
   -------------------------------------------------------------------
   문법 : CREATE DATABASE [데이터베이스 이름];
          DROP   DATABASE [데이터베이스 이름];
   =================================================================== */


/* ── 1. 데이터베이스 생성 (p.19 ~ p.20) ───────────────────────────── */

-- 1) 기존 DB 목록 확인
SHOW DATABASES;

-- 2) 실습용 testdb 생성
CREATE DATABASE testdb;

-- 3) 생성 확인 (목록에 testdb가 추가됨)
SHOW DATABASES;


/* ── 2. 데이터베이스 삭제 (p.21 ~ p.22) ───────────────────────────── */

-- 1) 실습용 testdb 삭제
--    ※ DB 안의 모든 테이블·데이터가 함께 사라지므로 주의
DROP DATABASE testdb;

-- 2) 삭제 확인 (목록에서 testdb가 사라짐)
SHOW DATABASES;


/* ── 참고 : 에러 없이 실행하기 ───────────────────────────────────────
   IF NOT EXISTS / IF EXISTS 를 붙이면 이미 있거나 없는 경우에도
   에러 없이 넘어간다. 스크립트를 반복 실행할 때 유용.

   CREATE DATABASE IF NOT EXISTS testdb;
   DROP   DATABASE IF EXISTS     testdb;
   ------------------------------------------------------------------ */
