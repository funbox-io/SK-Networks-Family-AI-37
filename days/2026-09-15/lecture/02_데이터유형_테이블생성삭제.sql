/* ── 테이블 생성을 위한 주요 데이터 유형 (p.23) ─────────────────────
   INT (정수형)
     목적 : 부호 있는 또는 부호 없는 정수 저장
     특징 : -2,147,483,648 ~ 2,147,483,647 범위의 정수
     사용 : 고유 ID, 수량, 횟수 등

   DECIMAL (정밀 십진수형)
     목적 : 정확한 십진수 값 저장
     특징 : DECIMAL(전체 자리수, 소수점 이하 자리수) 형식
     사용 : 가격, 금액, 세율 등 정확한 측정값

   VARCHAR (가변 길이 문자열형)
     목적 : 가변 길이 문자열 저장
     특징 : VARCHAR(저장 가능 최대 문자수) 형식으로 최대 길이 지정,
            실제 데이터 길이에 맞춰 저장 공간 사용
     사용 : 이름, 제목, 주소, 설명 등

   DATETIME (날짜 및 시간형)
     목적 : 날짜 및 시간 정보 저장
     특징 : YYYY-MM-DD HH:MM:SS 형식
     사용 : 생성 시간, 수정 시간, 이벤트 발생 시간 등
   ------------------------------------------------------------------ */


/* ── 1. 테이블 생성 (p.24 ~ p.25) ─────────────────────────────────── */

-- DB 생성 후 사용할 DB 지정
CREATE DATABASE testdb;
USE testdb;            -- 이후 모든 명령은 testdb를 대상으로 실행됨

-- test_table 생성
CREATE TABLE test_table (
    col1 INT,
    col2 VARCHAR(50),
    col3 DATETIME
);

-- 생성된 테이블 목록 확인
SHOW TABLES;


/* ── 2. 테이블 삭제 (p.26 ~ p.27) ─────────────────────────────────── */

-- test_table 삭제
DROP TABLE test_table;

-- 확인 (목록이 비어 있음)
SHOW TABLES;
