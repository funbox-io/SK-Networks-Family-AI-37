/* ── DDL : 구조를 다루는 명령어 ─────────────────────────────────────
   SHOW DATABASES;                      -- DB 목록 확인
   CREATE DATABASE db명;                -- DB 생성
   DROP   DATABASE db명;                -- DB 삭제
   USE db명;                            -- 사용할 DB 지정

   SHOW TABLES;                         -- 테이블 목록 확인
   CREATE TABLE 테이블명 ( 컬럼 자료형, … );
   DROP  TABLE 테이블명;
   DROP  TABLE IF EXISTS 테이블명;      -- 없어도 에러 X
   DESCRIBE 테이블명;                   -- 테이블 구조 확인
   ------------------------------------------------------------------ */


/* ── 데이터 유형 ────────────────────────────────────────────────────
   INT             정수            고유 ID, 수량, 횟수
   DECIMAL(p, s)   정밀 십진수      가격, 금액, 세율
   VARCHAR(n)      가변 문자열      이름, 제목, 주소
   DATETIME        날짜+시간        생성/수정 시간 (YYYY-MM-DD HH:MM:SS)
   ------------------------------------------------------------------ */


/* ── 제약조건 ───────────────────────────────────────────────────────
   PRIMARY KEY      행을 유일하게 식별, 테이블당 1개, Unique + NOT NULL
   NOT NULL         NULL 입력 금지, 무결성 보장
   AUTO_INCREMENT   INT 컬럼에만, 테이블당 1개, 1씩 자동 증가
   FOREIGN KEY      다른 테이블 PK 참조, 부모-자식 관계, 참조 무결성
   ------------------------------------------------------------------ */


/* ── DML : 데이터를 다루는 명령어 (CRUD) ────────────────────────────
   C  INSERT INTO 테이블명 (컬럼…) VALUES (값…);
   R  SELECT 컬럼… FROM 테이블명;
      SELECT * FROM 테이블명;
   U  UPDATE 테이블명 SET 컬럼 = 값 WHERE 조건;
   D  DELETE FROM 테이블명 WHERE 조건;

   ※ Safe Mode 에러 시 : SET sql_safe_updates = 0;
     (WHERE 없이 또는 PK가 아닌 조건으로 UPDATE/DELETE 할 때 발생)
   ------------------------------------------------------------------ */


/* ── 조회 조건 / 정렬 ───────────────────────────────────────────────
   WHERE 컬럼 = 값                 비교 : =, !=, >, <, >=, <=
   WHERE 조건A AND 조건B           논리 : AND, OR, NOT
   WHERE 컬럼 BETWEEN A AND B      범위 (A 이상 B 이하)
   WHERE 컬럼 IN (값1, 값2)        목록 중 일치
   WHERE 컬럼 LIKE '패턴'          패턴 (% = 글자수 무제한, _ = 한 글자)
   ORDER BY 컬럼 ASC | DESC        정렬 (ASC 기본값)
   LIMIT n                         상위 n건만 출력

   작성 순서 : SELECT → FROM → WHERE → ORDER BY → LIMIT
   ------------------------------------------------------------------ */
