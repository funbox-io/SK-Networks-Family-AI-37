/* ===================================================================
   [03] 인덱스(Index)의 개념과 필요성
   교재 : p.115  (교재는 개념만 다루며, 아래 코드는 개념을 눈으로 확인하는 참고 실습)
   선행 : world 샘플 DB
   -------------------------------------------------------------------
   인덱스(Index)
     1) 데이터를 쉽고 빠르게 찾기 위해 특정 기준(ID 순, 알파벳 순)으로 정렬한 뒤,
        일정 범위의 값으로 묶어 그룹(1~1000 은 A그룹, 1001~2000 은 B그룹 …)으로
        설정한 피라미드(Tree) 구조
     2) 인덱스가 지정된 컬럼을 검색하면 몇 번의 대소 비교만으로 원하는 행을 즉시 찾는다

   Full Table Scan (전체 테이블 스캔)
     - 인덱스가 없을 때 발생
     - 첫 행부터 마지막 행까지 일일이 다 읽어서 조건 비교 (데이터가 많을수록 극도로 느려짐)
   Index Scan (인덱스 스캔)
     - 인덱스가 설정되어 있을 때 발생
     - 정렬된 인덱스(Tree)를 타고 내려가 해당 데이터만 콕 집어서 추출 (검색 속도 극대화)
   =================================================================== */

USE world;


/* ── 1. 현재 테이블에 어떤 인덱스가 있는지 확인 ───────────────────────
   PRIMARY KEY 를 만들면 그 컬럼에는 인덱스가 자동으로 생긴다.
   ------------------------------------------------------------------ */
SHOW INDEX FROM city;
-- city 에는 PRIMARY(ID) 와 CountryCode 인덱스가 있다. Name 컬럼에는 인덱스가 없다.


/* ── 2. EXPLAIN — 이 쿼리가 어떤 방식으로 실행될지 미리 보기 ─────────
   type 컬럼을 본다 :  ALL  = Full Table Scan
                       ref / const / range = 인덱스 사용
   rows 컬럼 = 읽을 것으로 예상되는 행 수
   ------------------------------------------------------------------ */

-- 1) 인덱스가 있는 컬럼(PK)으로 검색 → type = const, rows = 1
EXPLAIN SELECT * FROM city WHERE ID = 2331;

-- 2) 인덱스가 없는 컬럼(Name)으로 검색 → type = ALL, rows ≈ 4079 (전체를 다 읽는다)
EXPLAIN SELECT * FROM city WHERE Name = 'Seoul';


/* ── 3. 인덱스 생성 후 다시 비교 ─────────────────────────────────────
   문법 : CREATE INDEX 인덱스명 ON 테이블명 (컬럼명);
          DROP   INDEX 인덱스명 ON 테이블명;
   ------------------------------------------------------------------ */
CREATE INDEX idx_city_name ON city (Name);

-- 같은 쿼리를 다시 EXPLAIN → type = ref, rows = 1 (인덱스 스캔으로 바뀜)
EXPLAIN SELECT * FROM city WHERE Name = 'Seoul';

-- 실제 조회 (결과는 인덱스 유무와 상관없이 동일하다. 달라지는 것은 "찾는 방법"뿐)
SELECT ID, Name, CountryCode, Population FROM city WHERE Name = 'Seoul';


/* ── 4. 인덱스가 소용없는 검색 — 앞에 % 가 붙은 LIKE ──────────────────
   인덱스는 "정렬된 값의 앞부분"으로 찾아 내려가는 구조라서,
   '%김%' 처럼 시작 글자를 모르면 정렬을 활용할 수 없어 다시 Full Scan 이 된다.
   ------------------------------------------------------------------ */
EXPLAIN SELECT * FROM city WHERE Name LIKE 'Seo%';    -- type = range  (인덱스 사용)
EXPLAIN SELECT * FROM city WHERE Name LIKE '%eoul';   -- type = ALL    (인덱스 무용지물)


/* ── 5. 실습용 인덱스 정리 (샘플 DB 를 원래대로) ─────────────────────── */
DROP INDEX idx_city_name ON city;
SHOW INDEX FROM city;


/* ── 참고 : 인덱스는 공짜가 아니다 ───────────────────────────────────
   - 조회(SELECT)는 빨라지지만, INSERT / UPDATE / DELETE 때마다 인덱스도 함께
     갱신해야 하므로 쓰기 성능은 떨어지고 디스크 공간도 추가로 쓴다.
   - 그래서 WHERE · JOIN · ORDER BY 에 자주 쓰이는 컬럼에만 골라서 건다.
   ------------------------------------------------------------------ */
