"""
basic_02.py
교재 p.123~127 : streamlit 기능 - 텍스트 출력 / 사용자 입력 위젯 생성

실행 방법 : 터미널에서  streamlit run basic_02.py
"""

# 라이브러리 임포트 (교재 p.123 : import streamlit as st)
import streamlit as st


# =====================================================================
# 1. 텍스트 출력 (교재 p.124)
#    화면에 제목, 본문, 안내 문구 등의 글자를 출력해 주는 기능
# =====================================================================

# st.title()    : 가장 큰 메인 제목
st.title("SK네트웍스 Family AI 캠프")

st.divider()  # 구분선(가로줄) 출력

# st.header()   : 대분류 주제 제목
st.header("Python Web 대시보드 만들기")

# st.subheader(): 중분류 세부 제목
st.subheader("Sub func text output")

st.divider()

# st.write()    : print() 대신 사용하는 만능 출력 함수
#                 (문자, 숫자, 딕셔너리 등 무엇이든 알아서 출력)
st.write("Python write() - print() 대신 사용")

# st.caption()  : 작은 주석이나 부연 설명
st.caption("본 시스템은 순수 파이썬 문법으로 작성되었습니다.")


# =====================================================================
# 2. 사용자 입력 위젯 (교재 p.126~127)
#    사용자가 누른 값에 따라 다르게 반응하는 '동적인 웹 서비스'를 만드는 요소
# =====================================================================

# ---------------------------------------------------------------------
# 2-1. 버튼 : 클릭하면 True, 안 누르면 False 반환
#      → 반환값이 True/False 이므로 항상 if 조건문과 함께 사용한다.
# ---------------------------------------------------------------------
st.divider()
st.header("1. 버튼 박스")

if st.button("버튼: 인사하기"):
    st.write("== 반가워요. ==")
else:
    st.write("== 버튼: 대기 ==")


# ---------------------------------------------------------------------
# 2-2. 체크박스 : 체크 여부(True/False)를 확인 → 약관 동의 등에 사용
# ---------------------------------------------------------------------
st.divider()
st.header("2. 체크박스")

is_checked = st.checkbox("체크박스: ")
st.write(f"== 반환된 값: {is_checked} ==")


# ---------------------------------------------------------------------
# 2-3. 라디오 버튼 : 리스트 항목 중 딱 하나만 선택 → 선택된 '값' 반환
# ---------------------------------------------------------------------
st.divider()
st.header("3. 라디오 박스")

# 위젯에 공통으로 사용할 리스트 데이터
cont_types = ['일반 고객', 'VIP 고객', '가입 고객']

radio_value = st.radio("분석할 고객 유형:", cont_types)
st.write(f"== 라디오 값: {radio_value} ==")


# ---------------------------------------------------------------------
# 2-4. 선택 박스(드롭다운) : 드롭다운 메뉴로 하나만 선택
# ---------------------------------------------------------------------
st.divider()
st.header("4. 선택 박스(드롭다운)")

select_value = st.selectbox("조회 고객 타입 선택:", cont_types)
st.write(f"== 선택 박스: {select_value} ==")


# ---------------------------------------------------------------------
# 2-5. 멀티 선택 : 여러 개를 동시에 선택 → 파이썬 list 반환
# ---------------------------------------------------------------------
st.divider()
st.header("5. 멀티 선택")

multi_value = st.multiselect("고객 유형 다중 선택:", cont_types)
st.write(f"== 멀티 선택: {multi_value} ==")


# ---------------------------------------------------------------------
# 2-6. 텍스트 입력 : 사용자가 문자열을 직접 입력 (기본값은 빈 문자열 "")
# ---------------------------------------------------------------------
st.divider()
st.header("6. 텍스트 입력")

text_data = st.text_input("텍스트 입력:")
if text_data:  # 입력값이 있을 때만 출력
    st.write(f"== 텍스트 입력: {text_data} ==")


# ---------------------------------------------------------------------
# 2-7. 숫자 입력 : 사용자가 숫자를 입력 (정수/실수 반환, 기본값 0.0)
# ---------------------------------------------------------------------
st.divider()
st.header("7. 숫자 입력")

int_data = st.number_input("숫자 입력:")
if int_data:  # 0이 아닐 때만 출력
    st.write(f"== 숫자 입력: {int_data} ==")
