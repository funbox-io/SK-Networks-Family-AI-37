"""
basic_03.py
교재 p.129~131 : streamlit 기능 - 데이터 표출 & 차트 생성 / 레이아웃 & 컨테이너 생성

실행 방법 : 터미널에서  streamlit run basic_03.py
"""

# 라이브러리 임포트
import streamlit as st


# 화면 전체에서 공통으로 사용할 딕셔너리 데이터
# (형태 : {"항목명": 값} → streamlit이 바로 차트로 그려준다)
data_value = {'1명': 120, '2명': 190, '3명': 260, '4명': 310}


# =====================================================================
# 1. 데이터 표출 & 차트 생성 (교재 p.129)
#    딕셔너리(dict)나 리스트(list)를 숫자 카드, 표, 그래프로 변환해 출력
# =====================================================================

# st.metric() : 핵심 성과 지표(KPI)와 이전 대비 변화량(Delta)을 크게 강조
st.metric(label="오늘의 총매출", value="8,000원", delta="+158")

st.divider()

# st.bar_chart() : 딕셔너리를 그대로 전달하면 즉시 막대그래프로 그려준다.
#   - color      : 막대 색상
#   - horizontal : True → 수평(가로) 막대 그래프
st.bar_chart(data=data_value, color="green", horizontal=True)


# =====================================================================
# 2. 레이아웃 & 컨테이너 생성 (교재 p.131)
#    화면을 좌우로 나누거나(컬럼), 메뉴판을 만들거나(사이드바),
#    탭으로 분할해 주는 '화면 정리 정돈' 기능
# =====================================================================

st.divider()

# ---------------------------------------------------------------------
# 2-1. 사이드바 (st.sidebar) : 화면 왼쪽에 메뉴/설정창 공간을 만든다.
#      with 구문 안쪽에 들여쓰기로 작성한 요소가 모두 사이드바에 붙는다.
# ---------------------------------------------------------------------
with st.sidebar:
    st.header("메뉴판")
    menu = st.radio("이동", ['홈', '상세보기'])


# ---------------------------------------------------------------------
# 2-2. 다단 컬럼 (st.columns) : 메인 화면을 가로로 균등 분할(1:1)
#      반환된 컬럼 객체를 변수에 할당한 뒤 with 로 각 구역에 요소를 붙인다.
# ---------------------------------------------------------------------
col1, col2 = st.columns(2)

with col1:
    st.subheader("왼쪽 구역")

    # st.expander() : 평소에는 접어두었다가 클릭할 때만 펼쳐지는 영역
    with st.expander("원본 데이터"):
        st.write(data_value)

with col2:
    st.subheader("오른쪽 구역")

    with st.expander("수평 막대 그래프"):
        st.bar_chart(data=data_value, color="green", horizontal=True)


# ---------------------------------------------------------------------
# 2-3. 탭 나누기 (st.tabs) : 한 화면 안에서 탭을 눌러 내용을 전환
#      반환된 탭 객체를 각각 변수에 할당해 화면을 구현한다.
# ---------------------------------------------------------------------
st.divider()

tab1, tab2, tab3 = st.tabs(['차트 보기', '데이터 보기', '정보 보기'])

with tab1:
    st.subheader("데이터 시각화")
    st.bar_chart(data=data_value, color='red', horizontal=True)

with tab2:
    st.subheader("원본 데이터")
    st.write(data_value)

with tab3:
    st.subheader("정보")
    st.write("이 앱은 st.write() 함수를 활용해 만들었습니다.")
