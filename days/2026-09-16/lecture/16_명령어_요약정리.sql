/* ── 집계 함수 ──────────────────────────────────────────────────────
   COUNT(*)      전체 행 수 (NULL 포함)
   COUNT(컬럼)   NULL 이 아닌 행 수
   SUM / AVG / MAX / MIN (컬럼)     NULL 은 계산에서 제외
   ROUND(값, n)                     소수 n 자리 반올림
   ------------------------------------------------------------------ */


/* ── 그룹화 · 그룹 조건 ─────────────────────────────────────────────
   GROUP BY 컬럼                    같은 값끼리 묶어 집계
   HAVING 집계조건                  그룹화 '후' 필터 (집계 함수 사용 O)
   WHERE  행조건                    그룹화 '전' 필터 (집계 함수 사용 X)

   작성 순서 : SELECT → FROM → JOIN → WHERE → GROUP BY → HAVING → ORDER BY → LIMIT
   실행 순서 : FROM → JOIN → WHERE → GROUP BY → HAVING → SELECT → ORDER BY → LIMIT
   ------------------------------------------------------------------ */


/* ── 조건부 입력 ────────────────────────────────────────────────────
   INSERT IGNORE INTO 테이블 VALUES (…);                   PK 중복이면 Skip
   INSERT INTO 테이블 VALUES (…)
   ON DUPLICATE KEY UPDATE 컬럼 = 컬럼 + 값;                없으면 INSERT, 있으면 UPDATE
   ------------------------------------------------------------------ */


/* ── 데이터 타입 ────────────────────────────────────────────────────
   정수   TINYINT(1B) < SMALLINT(2B) < INT(4B, ±21억) < BIGINT(8B)
   실수   FLOAT, DOUBLE (근사값)  /  DECIMAL(P, S) (정확한 값, 금액)
   문자   CHAR(N) 고정  /  VARCHAR(N) 가변  /  TEXT, LONGTEXT(최대 4GB)
   날짜   DATE (YYYY-MM-DD)  /  TIME  /  DATETIME (시분초 포함)
   ------------------------------------------------------------------ */


/* ── 사용자 정의 변수 ───────────────────────────────────────────────
   SET @변수 = 값;                  세션 동안 유지
   SELECT 집계 INTO @변수 FROM …;   조회 결과를 변수에 저장
   LIMIT @변수  ✕  → PREPARE … EXECUTE … USING @변수
   ------------------------------------------------------------------ */


/* ── 형변환 ─────────────────────────────────────────────────────────
   CAST(값 AS 타입)  /  CONVERT(값, 타입)
   타입 : SIGNED, UNSIGNED, CHAR, DECIMAL, DATE, DATETIME
          (INT, VARCHAR 는 문법 에러)
   CAST(123.5 AS SIGNED) = 124     실수 → 정수는 반올림
   '100' + '200' = 300             묵시적 형변환 (문자 연결은 CONCAT)
   ------------------------------------------------------------------ */


/* ── 문자열 함수 ────────────────────────────────────────────────────
   CONCAT(a, b, …)        연결
   SUBSTRING(s, p, l)     p 번째(1부터)부터 l 글자
   LENGTH(s)              바이트 수 (한글 1자 = 3)
   CHAR_LENGTH(s)         글자 수
   UPPER(s) / LOWER(s)    대문자 / 소문자
   REPLACE(s, f, t)       f → t 치환
   ------------------------------------------------------------------ */


/* ── 날짜 · 시간 함수 ───────────────────────────────────────────────
   NOW() / SYSDATE()                  현재 날짜+시간
   CURDATE() / CURTIME()              현재 날짜 / 현재 시간
   DATEDIFF(d1, d2)                   d1 - d2 일수
   DATE_ADD(d, INTERVAL n 단위)       기간 더하기 (DATE_SUB 빼기)
   DATE_FORMAT(d, '%Y-%m-%d %H:%i')   형식 변환
   ------------------------------------------------------------------ */


/* ── 제어 흐름 · NULL 처리 ──────────────────────────────────────────
   IF(조건, 참값, 거짓값)             조건이 NULL 이면 거짓값
   IFNULL(값, 대체값)                 NULL 이면 대체값
   CASE WHEN 조건 THEN 값 … ELSE 기본값 END
        → 위에서부터 평가, ELSE 생략 시 NULL, END 필수
   NULL 비교는 = 가 아니라 IS NULL / IS NOT NULL
   ------------------------------------------------------------------ */


/* ── JOIN ───────────────────────────────────────────────────────────
   FROM A INNER JOIN B ON A.키 = B.키     교집합
   FROM A LEFT  JOIN B ON A.키 = B.키     A 전체 + 매칭 (없으면 NULL)
   FROM A RIGHT JOIN B ON A.키 = B.키     B 전체 + 매칭 (없으면 NULL)
   LEFT JOIN … WHERE B.키 IS NULL          A 에만 있는 행 (차집합)
   CROSS JOIN                              모든 조합 (카테시안 곱)
   SELF JOIN                               자기 자신과 조인 (조직도 등)
   ※ 같은 이름 컬럼은 반드시 '별칭.컬럼' 으로 구분
   ------------------------------------------------------------------ */
