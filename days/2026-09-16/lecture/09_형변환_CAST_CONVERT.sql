/* ===================================================================
   [09] 명시적 형변환과 묵시적 형변환
   교재 : p.82 ~ p.86
   선행 : 없음 (테이블을 쓰지 않음)
   -------------------------------------------------------------------
   명시적 형변환 (Explicit Conversion)
     : 개발자가 CAST / CONVERT 로 타입을 직접 바꾸는 방식
       CAST(값 AS 데이터타입)
       CONVERT(값, 데이터타입)

   ★ 형변환 함수 안에서는 '전용 타입'을 써야 한다
       정수   → SIGNED (또는 UNSIGNED)      ※ INT     사용 불가
       문자열 → CHAR   (또는 CHAR(N))       ※ VARCHAR 사용 불가
       실수   → DECIMAL                     ※ 교재 기준 FLOAT, DOUBLE 사용 불가
                                               (MySQL 8.0.17 이상은 FLOAT·DOUBLE 도 허용)
       그 외  → DATE, DATETIME, TIME 등

   묵시적 형변환 (Implicit Conversion)
     : 형변환 함수를 쓰지 않아도 연산자·문맥에 따라 MySQL 이 자동 변환
   =================================================================== */


/* ── 1. 명시적 형변환 : 문자열 → 정수 (p.83 ~ p.84) ─────────────────── */

SELECT CAST('100' AS SIGNED) + CAST('200' AS SIGNED) AS 합계;   -- 300

-- CONVERT 로 같은 결과
SELECT CONVERT('100', SIGNED) + CONVERT('200', SIGNED) AS 합계;


/* ── 2. 명시적 형변환 : 실수 → 정수 (p.83, p.85) ────────────────────── */

SELECT CAST(123.456 AS SIGNED) AS 정수변환;   -- 123

-- ※ 버림이 아니라 '반올림'된다
SELECT CAST(123.5 AS SIGNED) AS 반올림확인;   -- 124


/* ── 3. 묵시적 형변환 : 문자열이 자동으로 숫자로 계산됨 (p.83, p.86) ─── */

SELECT '100' + '200' AS 묵시적합계;   -- 300 (문자열 연결이 아니라 덧셈!)

-- ※ 파이썬은 '100' + '200' = '100200' 이지만 SQL 의 + 는 항상 '숫자 덧셈'
--   문자열을 이어 붙이려면 CONCAT('100', '200') 을 쓴다 (10번 파일)
SELECT CONCAT('100', '200') AS 문자열연결;   -- '100200'

-- 숫자로 시작하는 문자열은 앞 숫자까지만 읽는다 (경고 발생)
SELECT '10abc' + 5 AS 앞숫자만;   -- 15
SHOW WARNINGS;


/* ── 4. 그 밖의 변환 예시 ─────────────────────────────────────────── */

SELECT
    CAST(3.14159 AS DECIMAL(5, 2)) AS 실수자리수지정,   -- 3.14
    CAST(2026 AS CHAR)             AS 숫자를문자로,     -- '2026'
    CAST('2026-09-16' AS DATE)     AS 문자를날짜로;     -- 2026-09-16


